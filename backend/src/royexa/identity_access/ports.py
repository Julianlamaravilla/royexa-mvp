from __future__ import annotations

from typing import Protocol, Self

from royexa.identity_access.domain import Credential, Session


class AuthRepository(Protocol):
    def credential(self, user_id: str) -> Credential | None: ...
    def save_credential(self, credential: Credential) -> None: ...
    def demo_users(self) -> list[str]:
        """Users that still have the demonstration password."""
        ...

    def sessions_of(self, user_id: str) -> list[Session]: ...
    def add_session(self, session: Session) -> None: ...
    def session(self, token_hash: str) -> Session | None: ...
    def save_session(self, session: Session) -> None:
        """Only the revocation ever changes."""
        ...


class AuthUnitOfWork(Protocol):
    auth: AuthRepository

    def __enter__(self) -> Self: ...
    def __exit__(self, *exc_info: object) -> None: ...
    def commit(self) -> None: ...
